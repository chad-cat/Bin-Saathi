/**
 * Deterministic offline search over LOCAL_RULES.
 * Matches keys, English names, Hindi names, and aliases.
 */
export function searchRules(query: string, lang: 'en' | 'hi' = 'en'): RuleEntry[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];

  const results: { rule: RuleEntry; score: number }[] = [];

  for (const rule of Object.values(LOCAL_RULES)) {
    let score = 0;

    // Exact key or name match
    if (rule.itemKey.toLowerCase() === q) score += 100;
    if (rule.nameEn.toLowerCase() === q) score += 90;
    if (rule.nameHi.toLowerCase() === q) score += 90;

    // Substring in key or name
    if (rule.itemKey.toLowerCase().includes(q)) score += 40;
    if (rule.nameEn.toLowerCase().includes(q)) score += 50;
    if (rule.nameHi.toLowerCase().includes(q)) score += 50;

    // Match in aliases
    for (const alias of rule.aliasesEn) {
      if (alias.toLowerCase() === q) {
        score += 150;
        break;
      } else if (alias.toLowerCase().startsWith(q) || q.startsWith(alias.toLowerCase())) {
        score += 45;
      } else if (alias.toLowerCase().includes(q)) {
        score += 25;
      }
    }

    for (const alias of rule.aliasesHi) {
      if (alias.toLowerCase() === q) {
        score += 150;
        break;
      } else if (alias.toLowerCase().startsWith(q) || q.startsWith(alias.toLowerCase())) {
        score += 45;
      } else if (alias.toLowerCase().includes(q)) {
        score += 25;
      }
    }

    if (score > 0) {
      results.push({ rule, score });
    }
  }

  results.sort((a, b) => b.score - a.score);
  return results.map((r) => r.rule);
}
